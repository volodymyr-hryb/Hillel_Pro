color = input("Введіть колір (англійською): ").strip().lower()

if color == "red":
    print("зупинитися")
elif color == "yellow":
    print("очікувати або підготуватися відповідно до навчальної моделі")
elif color == "green":
    print("рух дозволено за умови безпеки")
else:
    print("невідомий сигнал")




